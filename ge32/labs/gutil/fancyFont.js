/**
 * 转换文字为指定样式字体
 * @param {string} text - 要转换的字符串
 * @param {string} style - 样式名称（参见 STYLES_FONT 的 key）
 * @returns {string} - 转换后的字符串
 */
export function toFancyFont(text, style = "bold") {
  const normalUpper = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
  const normalLower = "abcdefghijklmnopqrstuvwxyz";
  const selected = STYLES_FONT[style] || STYLES_FONT["boldScript"];
  const fancyUpper = Array.from(selected.upper);
  const fancyLower = Array.from(selected.lower);

  return Array.from(text).map(char => {
    let index = normalUpper.indexOf(char);
    if (index !== -1) return fancyUpper[index] || char;
    index = normalLower.indexOf(char);
    if (index !== -1) return fancyLower[index] || char;
    return char;
  }).join("");
}

/**
 * 获取支持的字体样式列表
 */
export function getFancyFontStyles() {
  return Object.keys(STYLES_FONT);
}

